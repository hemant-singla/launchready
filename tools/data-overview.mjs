// Writes docs/DATA.md: a readable summary of the fictional dataset and the
// baseline verdicts, generated from the data files and the logic (no hand edits).
// Run: node tools/data-overview.mjs
import { writeFileSync } from 'node:fs';
import { loadData } from '../src/data.js';
import { computeAll } from '../src/engine.js';
import { SCENARIOS } from '../src/scenarios.js';
import { openTickets } from '../src/software.js';

const d = await loadData();
const r = computeAll(d);
const t = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((x) => `| ${x.join(' | ')} |`)].join('\n');
const L = { ready: 'Ready', 'at-risk': 'At risk', blocked: 'Blocked' };
const out = [];
out.push(`# LaunchReady data overview\n\n> Generated by \`node tools/data-overview.mjs\` from \`data/*.json\` and \`src/\`. Fictional company (${d.config.company}), fictional data. As of ${d.config.asOf}.\n`);
out.push('## Line-up and baseline verdicts\n');
out.push(t(['Model', 'Line', 'Chipset', 'Launch', 'First build', 'Software ready', 'Software', 'Supply', 'Verdict'],
  r.models.map((m) => [m.name, m.segment, m.chipset, m.launchDate, m.firstBuildUnits.toLocaleString('en-US'), `${m.eta.early} – ${m.eta.late}`, L[m.software.status], L[m.supply.status], `**${L[m.status]}**`])));
out.push('\n## Chipsets\n');
out.push(t(['Chipset', 'New?', 'Test boards', 'Code deadline', 'Planned test start', 'Computed test start', 'Open tickets (C/M/m)', 'Avg new code'],
  d.chipsets.map((c) => {
    const e = r.chipsets[c.id].eta; const o = openTickets(d, c.id); const s = d.submissions.filter((x) => x.chipset === c.id);
    const k = (v) => o.filter((x) => x.severity === v).length;
    return [c.id, c.isNew ? 'new' : 'reused', c.testBoards, c.codeDeadline, c.plannedTestStart, e.testStart ?? '?', `${k('critical')}/${k('major')}/${k('minor')}`, `${Math.round(s.reduce((a, x) => a + x.newCodePct, 0) / s.length)}%`];
  })));
out.push(`\nTickets: ${d.tickets.length} in total (${d.tickets.filter((x) => x.status === 'open').length} open), raised by testing teams and clients on the three chipsets already in testing.\n`);
out.push('## Late or missing code submissions\n');
out.push(t(['Chipset', 'Team', 'Due', 'Expected'], d.submissions.filter((s) => !s.submittedOn && s.expectedOn > s.dueDate).map((s) => [s.chipset, s.team, s.dueDate, s.expectedOn])));
out.push('\n## Parts: free stock and deliveries\n');
out.push(t(['Part', 'Name', 'Used by', 'On hand', 'Allocated', 'Free'], d.parts.map((p) => {
  const st = d.stock.filter((s) => s.part === p.id); const sum = (f) => st.reduce((a, s) => a + f(s), 0);
  return [p.id, p.name, d.bom.filter((b) => b.part === p.id).map((b) => b.chipset).join(', ') || 'substitute', sum((s) => s.onHand), sum((s) => s.allocated), sum((s) => s.onHand - s.allocated)];
})));
out.push('\n');
out.push(t(['PO', 'Part', 'Qty', 'Planned', 'Current', 'Status', 'For', 'Note'], d.deliveries.map((x) => [x.id, x.part, x.qty, x.originalEta, x.eta ?? '**no date**', x.status, x.forChipset ?? 'any', x.note])));
out.push('\n## Approved substitutes\n');
out.push(t(['Part', 'Substitute', 'Approved for', 'Driver change'], d.substitutes.map((s) => [s.part, s.substitute, s.approvedFor.join(', '), `${s.driverTeam}, ${s.driverChangeDays[0]}–${s.driverChangeDays[1]} days`])));
out.push('\n## What each scenario changes\n');
for (const [, s] of Object.entries(SCENARIOS)) {
  const after = computeAll(s.apply(d));
  const changed = after.models.filter((m) => m.status !== r.models.find((x) => x.id === m.id).status);
  out.push(`### ${s.title}\n${s.summary}\n`);
  out.push(t(['Model', 'Before', 'After', 'Why (from the code)'], changed.map((m) => [m.name, L[r.models.find((x) => x.id === m.id).status], `**${L[m.status]}**`, [...m.software.reasons, ...m.supply.reasons].join('; ')])));
  out.push('');
}
writeFileSync(new URL('../docs/DATA.md', import.meta.url), out.join('\n') + '\n');
console.log('wrote docs/DATA.md');
